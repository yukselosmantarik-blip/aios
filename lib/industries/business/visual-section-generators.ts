import type { CompiledWebsiteProject } from "@/lib/website-compiler/types";
import { businessProfileForComponentExport } from "@/lib/industries/restaurant/landing";
import { businessProfileToFooterProfile } from "@/lib/industries/business/footer-adapter";
import {
  generatePremiumSectionWrapper,
  headerComment,
  premiumSectionImports,
  STYLE_IMPORT,
} from "@/lib/project-generator/visual-component-utils";
import { isClientComponent } from "@/lib/project-generator/react-component-utils";

function requireBusinessProfile(project: CompiledWebsiteProject) {
  if (!project.businessProfile) {
    throw new Error("Business section generators require businessProfile on the compiled project");
  }
  return project.businessProfile;
}

export function generateBusinessContentSectionSource(): string {
  return generatePremiumSectionWrapper("ContentSection", [
    "          {(() => {",
    "            const paragraphs =",
    "              section.contentBlocks.length > 0 ? section.contentBlocks : (section.contentLines ?? []);",
    "            if (paragraphs.length === 0) {",
    '              return section.description ? (',
    '                <p className="max-w-3xl text-[length:var(--font-size-md)] leading-relaxed text-[var(--color-text-muted)]">',
    "                  {section.description}",
    "                </p>",
    "              ) : null;",
    "            }",
    "            return (",
    '              <Stack gap="md" className="max-w-3xl">',
    "                {paragraphs.map((block) => (",
    '                  <p key={block} className="text-[length:var(--font-size-md)] leading-relaxed text-[var(--color-text-muted)]">',
    "                    {block}",
    "                  </p>",
    "                ))}",
    "              </Stack>",
    "            );",
    "          })()}",
    "          {section.primaryCTA && section.primaryCtaHref ? (",
    "            <ButtonLink cta={{ label: section.primaryCTA, href: section.primaryCtaHref, variant: 'primary' }} />",
    "          ) : null}",
  ], ["import { ButtonLink } from './ButtonLink';"]);
}

export function generateBusinessFeatureGridSectionSource(): string {
  return generatePremiumSectionWrapper("FeatureGridSection", [
    "          {(() => {",
    "            const items = section.contentBlocks.length > 0 ? section.contentBlocks : (section.contentLines ?? []);",
    "            if (items.length === 0) {",
    "              return null;",
    "            }",
    "            return (",
    '              <ResponsiveGrid columns={3}>',
    "                {items.map((item) => {",
    "                  const splitAt = item.indexOf(': ');",
    "                  const title = splitAt > 0 ? item.slice(0, splitAt) : item;",
    "                  const description = splitAt > 0 ? item.slice(splitAt + 2) : '';",
    "                  const initial = title.trim().charAt(0).toUpperCase() || '?';",
    "                  return (",
    '                    <li key={item}>',
    '                      <Card variant="interactive" as="article">',
    '                        <Stack gap="sm">',
    '                          <span',
    '                            aria-hidden="true"',
    '                            className="flex h-10 w-10 items-center justify-center rounded-full bg-[var(--color-primary)]/10 text-sm font-[var(--font-weight-semibold)] text-[var(--color-primary)]"',
    "                          >",
    "                            {initial}",
    "                          </span>",
    '                          <h3 className="text-base font-[var(--font-weight-medium)]">{title}</h3>',
    "                          {description ? (",
    '                            <p className="text-[length:var(--font-size-sm)] text-[var(--color-text-muted)]">',
    "                              {description}",
    "                            </p>",
    "                          ) : null}",
    "                        </Stack>",
    "                      </Card>",
    "                    </li>",
    "                  );",
    "                })}",
    "              </ResponsiveGrid>",
    "            );",
    "          })()}",
  ], ["import { Card } from './Card';", "import { ResponsiveGrid } from './ResponsiveGrid';"]);
}

